import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const t0 = Date.now();
page.on('pageerror', (e) => console.log(`[pageerror +${Date.now() - t0}ms]`, e.message));
await page.goto('http://localhost:5210/?qa=1#/cloud-world-voxel', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__cwv?.view?.ready, undefined, { timeout: 90000 });
await page.waitForTimeout(3000);
console.log(`[+${Date.now() - t0}ms] ready`);
await page.evaluate(() => window.__cwv.teleport(47, 42, 'walk'));
await page.waitForTimeout(900);
console.log(`[+${Date.now() - t0}ms] badge:`, await page.evaluate(() => document.querySelector('.cwv-hud__badge')?.textContent));
await page.evaluate(() => window.__cwv.teleport(27, 49, 'walk'));
await page.waitForTimeout(700);
console.log(`[+${Date.now() - t0}ms] press e`);
await page.keyboard.press('e');
await page.waitForTimeout(600);
console.log(`[+${Date.now() - t0}ms] panel title:`, await page.evaluate(() => document.querySelector('.cwv-panel__title')?.textContent));
console.log(`[+${Date.now() - t0}ms] press Escape`);
await page.keyboard.press('Escape');
await page.waitForTimeout(400);
console.log(`[+${Date.now() - t0}ms] closed:`, await page.evaluate(() => !document.querySelector('.cwv-panel')));
await page.waitForTimeout(2000);
console.log(`[+${Date.now() - t0}ms] end`);
await browser.close();
