import { chromium } from 'playwright';
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
page.on('pageerror', (e) => console.log('[pageerror]', e.message));
await page.goto('http://localhost:5210/?qa=1#/cloud-world-voxel', { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__cwv?.view?.ready, undefined, { timeout: 90000 });
await page.waitForTimeout(2500);
console.log('--- loaded, no interaction; waiting 4s');
await page.waitForTimeout(4000);
console.log('--- opening panel via __cwv.open');
await page.evaluate(() => window.__cwv.open('portfolio_village'));
await page.waitForTimeout(1200);
console.log('panel in DOM:', await page.evaluate(() => !!document.querySelector('.cwv-panel')));
console.log('--- closing panel');
await page.evaluate(() => window.__cwv.close());
await page.waitForTimeout(1200);
console.log('--- opening via keyboard near sign (teleport first)');
await page.evaluate(() => window.__cwv.teleport(27, 49, 'walk'));
await page.waitForTimeout(800);
await page.keyboard.press('e');
await page.waitForTimeout(1200);
console.log('panel in DOM:', await page.evaluate(() => !!document.querySelector('.cwv-panel')));
console.log('--- done');
await browser.close();
