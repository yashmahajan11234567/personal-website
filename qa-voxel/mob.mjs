import { chromium } from 'playwright';
const OUT = 'qa-voxel/';
const browser = await chromium.launch();
const mob = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const mp = await mob.newPage();
const errs = [];
mp.on('pageerror', (e) => errs.push(e.message));
mp.setDefaultTimeout(90000);
await mp.goto('http://localhost:5210/#/cloud-world-voxel', { waitUntil: 'domcontentloaded' });
await mp.waitForFunction(() => window.__cwv, { timeout: 60000 });
await mp.waitForTimeout(4000);
await mp.screenshot({ path: OUT + 'm1-mobile-spawn.png', timeout: 60000 });
await mp.evaluate(() => { window.__cwv.view.zoom = 1.2; });
await mp.waitForTimeout(1500);
await mp.screenshot({ path: OUT + 'm1-mobile-wide.png', timeout: 60000 });
const stats = await mp.evaluate(() => { const r = window.__cwv.renderer; return { calls: r.info.render.calls, triangles: r.info.render.triangles, pixel: [r.domElement.width, r.domElement.height] }; });
console.log('mobile stats:', JSON.stringify(stats));
console.log('page errors:', errs.length ? errs : 'none');
await browser.close();
