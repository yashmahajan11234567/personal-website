import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, args: ['--use-angle=d3d11', '--enable-gpu'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on('pageerror', (e) => errs.push(String(e).slice(0,140)));
page.on('console', (m) => { if (m.type()==='error') errs.push(m.text().slice(0,140)); });
await page.goto('http://localhost:5195/', { waitUntil: 'domcontentloaded', timeout: 30000 });
await page.waitForSelector('[data-testid="loading-screen"]', { state: 'detached', timeout: 30000 });
await page.waitForTimeout(800);
await page.screenshot({ path: 'qa-screenshots-acceptance/gridpulse-baseline-open.png' });
await page.mouse.move(720, 500);
await page.waitForTimeout(400);
await page.screenshot({ path: 'qa-screenshots-acceptance/gridpulse-baseline-avatar.png' });
await page.mouse.move(400, 400);
await page.waitForTimeout(600);
await page.screenshot({ path: 'qa-screenshots-acceptance/gridpulse-baseline-move1.png' });
await page.mouse.move(900, 350);
await page.waitForTimeout(600);
await page.screenshot({ path: 'qa-screenshots-acceptance/gridpulse-baseline-move2.png' });
await page.mouse.move(720, 500);
await page.waitForTimeout(1500);
await page.screenshot({ path: 'qa-screenshots-acceptance/gridpulse-baseline-fade.png' });
console.log('ERRS:', errs.length);
await page.close();
await browser.close();
